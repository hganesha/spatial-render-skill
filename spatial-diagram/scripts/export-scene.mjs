#!/usr/bin/env node
// export-scene.mjs — compile a Scene Spec into a self-contained interactive HTML file.
// The output inlines Three.js, the Spatial Diagram runtime, and the scene spec:
// it runs from a file:// URL with no network and no build step.
//
// Usage:
//   node scripts/export-scene.mjs <scene.json> [-o out.html]
//   node scripts/export-scene.mjs --all            (builds examples/*/scene.json)
//
// Also used by capture-scene.mjs as a library (export { buildHtml } via import).

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { resolve, join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkScene } from './scene-validation.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const ENGINE_DIR = join(ROOT, 'kit/engine');
const VENDOR_DIR = join(ROOT, 'kit/vendor');

// Bundle order matters: dependencies first. Module style contract (see kit/engine/README):
//   * single-line named imports from './sibling.js'
//   * no default exports
//   * unique top-level names across all modules
const MODULE_ORDER = [
  'schema-data.js',
  'schema-validation.js',
  'spec-math.js',
  'materials.js',
  'geometry.js',
  'assembly.js',
  'annotations.js',
  'interactions.js',
  'renderer.js',
  'blueprint.js',
  'ui.js',
  'scene-compiler.js',
  'index.js'
];

export function bundleEngine() {
  const chunks = [];
  for (const name of MODULE_ORDER) {
    let src = readFileSync(join(ENGINE_DIR, name), 'utf8');
    // strip single-line relative imports
    src = src.replace(/^import\s+[^;]*?from\s+'\.\/[^']+';\s*$/gm, '');
    // strip named re-exports like `export { a, b };`
    src = src.replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '');
    // strip the `export ` keyword from declarations
    src = src.replace(/^export\s+(function|const|let|var|class)\s/gm, '$1 ');
    chunks.push(`// ---- module: ${name}\n${src}`);
  }
  return `/* Spatial Diagram Engine — bundled runtime (generated by export-scene.mjs) */
(function (global) {
'use strict';
${chunks.join('\n')}
global.SpatialDiagram = {
  createEngine: createEngine,
  ENGINE_VERSION: ENGINE_VERSION,
  normalizeSpec: normalizeSpec,
  validateSceneSpec: validateSceneSpec,
  auditScene: auditScene
};
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

function inlineScript(path) {
  return readFileSync(path, 'utf8');
}

export function buildHtml(scenePath, opts = {}) {
  const specRaw = readFileSync(scenePath, 'utf8');
  const spec = JSON.parse(specRaw);
  const validation = checkScene(spec);
  const errors = validation.structural.filter(i => i.level === 'error');
  if (errors.length) throw new Error('Invalid Scene Spec:\n' + errors.map(i => i.message).join('\n'));
  const sceneId = spec.scene?.id || basename(scenePath, '.json');
  const title = spec.scene?.title || sceneId;

  const threeJs = inlineScript(join(VENDOR_DIR, 'three.min.js'));
  const gltfExporter = inlineScript(join(VENDOR_DIR, 'GLTFExporter.js'));
  const engine = bundleEngine();

  const generated = new Date().toISOString();
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, user-scalable=no">
<title>${escapeHtml(title)} — Spatial Diagram</title>
<!--
  Self-contained interactive 3D diagram, generated by the spatial-diagram skill.
  Scene id: ${escapeHtml(sceneId)}
  Generated: ${generated}
  Fidelity: ${escapeHtml(spec.scene?.fidelity || 'representative')}
  This file embeds Three.js (MIT), the Spatial Diagram runtime, and the Scene Spec.
  The embedded Scene Spec is the editable source of truth (see the JSON export button).
-->
<style>
  html, body { margin:0; padding:0; height:100%; overflow:hidden; background:#0a0f18; }
  #stage { position:absolute; inset:0; }
  #stage canvas { display:block; }
  .sd-boot-error { position:absolute; inset:0; display:flex; align-items:center; justify-content:center;
    color:#e8eef6; font-family:system-ui,sans-serif; text-align:center; padding:24px; }
</style>
</head>
<body>
<div id="stage"></div>
<script>${threeJs}</script>
<script>${gltfExporter}</script>
<script>${engine}</script>
<script id="scene-spec" type="application/json">
${specRaw.replace(/</g, '\\u003c')}
</script>
<script>
(function () {
  try {
    var spec = JSON.parse(document.getElementById('scene-spec').textContent);
    var container = document.getElementById('stage');
    var engine = SpatialDiagram.createEngine({
      THREE: window.THREE,
      container: container,
      spec: spec,
      onEvent: function (evt) {
        if (evt && evt.type === 'scene:loaded') {
          console.log('[spatial-diagram] scene loaded:', evt.sceneId, evt.components + ' components');
        }
      }
    });
    window.sceneEngine = engine;
  } catch (e) {
    console.error(e);
    var d = document.createElement('div');
    d.className = 'sd-boot-error';
    d.textContent = 'Failed to start the Spatial Diagram runtime: ' + e.message;
    document.body.appendChild(d);
  }
})();
</script>
</body>
</html>`;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// --------------------------------------------------------------- CLI
async function main() {
  const argv = process.argv.slice(2);
  let jobs = [];
  if (argv.includes('--all')) {
    const exDir = join(ROOT, 'examples');
    for (const d of readdirSync(exDir)) {
      const scenePath = join(exDir, d, 'scene.json');
      try {
        if (statSync(scenePath).isFile()) jobs.push({ scenePath, outPath: join(exDir, d, 'index.html') });
      } catch { /* skip */ }
    }
  } else {
    const scenePath = argv.find((a) => !a.startsWith('-'));
    if (!scenePath) {
      console.error('Usage: node scripts/export-scene.mjs <scene.json> [-o out.html] | --all');
      process.exit(2);
    }
    const oIdx = argv.indexOf('-o');
    const outPath = oIdx >= 0 ? argv[oIdx + 1] : join(dirname(scenePath), 'index.html');
    jobs.push({ scenePath: resolve(scenePath), outPath: resolve(outPath) });
  }

  for (const job of jobs) {
    const html = buildHtml(job.scenePath);
    mkdirSync(dirname(job.outPath), { recursive: true });
    writeFileSync(job.outPath, html);
    const kb = Math.round(html.length / 1024);
    console.log(`✓ ${job.outPath}  (${kb} KB self-contained)`);
  }
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('export-scene.mjs')) {
  main();
}
