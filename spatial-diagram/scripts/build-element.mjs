#!/usr/bin/env node
// build-element.mjs — one script file that defines <spatial-diagram>, for docs, MDX and CMS embeds.
//
//   node scripts/build-element.mjs [-o dist/spatial-diagram.js]
//
//   <script src="spatial-diagram.js"></script>
//   <spatial-diagram src="scene.json" style="height:560px"></spatial-diagram>
//   <spatial-diagram render-mode="illustration" explode="1" tour-step="2">
//     <script type="application/json">{ ...inline Scene Spec... }</script>
//   </spatial-diagram>
//
// Attributes: src | inline JSON child, render-mode, explode (0..1), tour-step, autoplay ("false" disables
// scheduled behaviors), share-link ("true" mirrors view state into location.hash).
// `src` is fetched, so it needs http(s) — file:// pages should use inline JSON.
// Properties: element.engine (the runtime API), element.spec. Events: 'sd-ready', 'sd-event'.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {bundleEngine} from './export-scene.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const flag = process.argv.indexOf('-o');
const out = path.resolve(flag >= 0 ? process.argv[flag + 1] : path.join(ROOT, 'dist/spatial-diagram.js'));
const vendor = name => fs.readFileSync(path.join(ROOT, 'kit/vendor', name), 'utf8');
const element = `
(function () {
  'use strict';
  if (customElements.get('spatial-diagram')) return;
  class SpatialDiagramElement extends HTMLElement {
    static get observedAttributes() { return ['render-mode', 'explode', 'tour-step']; }
    connectedCallback() {
      if (this._started) return;
      this._started = true;
      if (!this.style.display) this.style.display = 'block';
      if (!this.style.position) this.style.position = 'relative';
      if (!this.style.height && !this.getAttribute('height')) this.style.height = '520px';
      this._stage = document.createElement('div');
      this._stage.style.cssText = 'position:absolute;inset:0;';
      this.appendChild(this._stage);
      this._load().catch(error => this._fail(error));
    }
    disconnectedCallback() { this.engine?.dispose(); this.engine = null; this._started = false; this._stage?.remove(); }
    async _load() {
      let spec;
      const inline = this.querySelector('script[type="application/json"]');
      if (inline) spec = JSON.parse(inline.textContent);
      else if (this.getAttribute('src')) {
        const response = await fetch(this.getAttribute('src'));
        if (!response.ok) throw new Error('Could not load ' + this.getAttribute('src') + ' (' + response.status + ')');
        spec = await response.json();
      } else throw new Error('<spatial-diagram> needs a src attribute or an inline JSON script.');
      if (this.getAttribute('autoplay') === 'false') spec.behaviors = [];
      const mode = this.getAttribute('render-mode');
      if (mode) spec.scene = Object.assign({}, spec.scene, { renderMode: mode });
      this.engine = SpatialDiagram.createEngine({ THREE: window.THREE, container: this._stage, spec: spec,
        urlState: this.getAttribute('share-link') === 'true',
        onEvent: event => this.dispatchEvent(new CustomEvent('sd-event', { detail: event })) });
      this.spec = this.engine.spec;
      this._apply();
      this.dispatchEvent(new CustomEvent('sd-ready', { detail: { engine: this.engine } }));
    }
    attributeChangedCallback() { if (this.engine) this._apply(); }
    _apply() {
      const mode = this.getAttribute('render-mode'), explode = this.getAttribute('explode'), step = this.getAttribute('tour-step');
      if (mode && mode !== this.engine.spec.scene.renderMode) this.engine.setRenderMode(mode);
      if (explode !== null && explode !== '') this.engine.explode(Number(explode), { duration: 900 });
      if (step !== null && step !== '') this.engine.tour.goTo(Number(step));
    }
    _fail(error) {
      console.error(error);
      const box = document.createElement('div');
      box.style.cssText = 'position:absolute;inset:0;display:flex;align-items:center;justify-content:center;padding:16px;font:13px system-ui;color:#b91c1c;background:#fff5f5;text-align:center;';
      box.textContent = 'Spatial diagram failed to load: ' + error.message;
      this.appendChild(box);
    }
  }
  customElements.define('spatial-diagram', SpatialDiagramElement);
})();
`;
const bundle = `/* <spatial-diagram> web component — Three.js r147 (MIT) + Spatial Diagram runtime. Generated by scripts/build-element.mjs. */
${vendor('three.min.js')}
${vendor('GLTFExporter.js')}
${bundleEngine()}
${element}`;
fs.mkdirSync(path.dirname(out), {recursive: true});
fs.writeFileSync(out, bundle);
console.log(`✓ <spatial-diagram> element → ${out} (${Math.round(bundle.length / 1024)} KB)`);
